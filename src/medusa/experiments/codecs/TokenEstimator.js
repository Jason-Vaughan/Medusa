'use strict';

/**
 * Deterministic Subword Token Estimator & Cost Calculator for Agent Communication Benchmarks.
 *
 * IMPORTANT: Never substitute raw UTF-8 byte counts for LLM token counts.
 * JSON punctuation, quotes, braces, colons, hex commit SHAs, and identifiers segment into
 * subword pieces differently than English prose under BPE tokenizers (cl100k_base / o200k_base / Claude / Gemini).
 *
 * This module implements a deterministic BPE-aligned subword segmenter that models:
 * - Punctuation/structural symbols (`{`, `}`, `[`, `]`, `:`, `,`, `"`, `=`, `(`, `)`)
 * - Hexadecimal commit SHAs & UUIDs (~2.5-3.5 chars per token in BPE)
 * - CamelCase / snake_case / kebab-case code identifiers & file paths
 * - Common English words vs. long/rare words (~4 chars per token piece)
 * - Whitespace attached to leading words (GPT/Claude BPE convention)
 */

const COMMON_SHORT_WORDS = new Set([
  'the', 'and', 'for', 'with', 'from', 'that', 'this', 'have', 'has', 'are', 'was', 'were',
  'will', 'can', 'not', 'but', 'all', 'any', 'new', 'fix', 'feat', 'test', 'tests', 'pass',
  'passed', 'hold', 'merge', 'main', 'branch', 'commit', 'issue', 'pull', 'request', 'review',
  'status', 'ready', 'complete', 'working', 'blocked', 'agent', 'lane', 'file', 'files', 'scope',
  'true', 'false', 'null', 'none', 'code', 'error', 'valid', 'node', 'nodes', 'edge', 'edges'
]);

const HEX_PATTERN = /^[0-9a-fA-F]{7,64}$/;

/**
 * Segments a string into BPE-like subword tokens and returns detailed token metrics.
 *
 * @param {string} text - Input wire text or prompt string to tokenize.
 * @returns {{ tokenCount: number, byteLength: number, charLength: number, segments: string[], method: string }}
 */
function estimateTokens(text) {
  if (typeof text !== 'string' || text.length === 0) {
    return {
      tokenCount: 0,
      byteLength: 0,
      charLength: 0,
      segments: [],
      method: 'deterministic-bpe-subword-v1'
    };
  }

  const byteLength = Buffer.byteLength(text, 'utf8');
  const charLength = text.length;
  const segments = [];

  // Match optional leading space + word/number, or structural punctuation runs, or newlines
  const rawMatches = text.match(/(\s?[A-Za-z0-9_]+|\n+|[^\sA-Za-z0-9_])/g) || [];

  for (const raw of rawMatches) {
    const trimmed = raw.trim();
    if (!trimmed) {
      segments.push(raw);
      continue;
    }

    // Single punctuation / structural character
    if (trimmed.length === 1 && /^[^A-Za-z0-9_]$/.test(trimmed)) {
      segments.push(raw);
      continue;
    }

    // Hex commit SHAs or UUID segments split densely in BPE (~2.5 chars per token)
    if (HEX_PATTERN.test(trimmed)) {
      for (let i = 0; i < trimmed.length; i += 3) {
        segments.push(trimmed.slice(i, i + 3));
      }
      continue;
    }

    // Pure numbers (1-3 digits per BPE token)
    if (/^\d+$/.test(trimmed)) {
      for (let i = 0; i < trimmed.length; i += 3) {
        segments.push(trimmed.slice(i, i + 3));
      }
      continue;
    }

    // Snake_case or camelCase identifiers
    const subParts = trimmed
      .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
      .split(/[_\s]+/)
      .filter(Boolean);

    for (const part of subParts) {
      const lower = part.toLowerCase();
      if (COMMON_SHORT_WORDS.has(lower) || part.length <= 5) {
        segments.push(part);
      } else {
        // Longer words split into ~4.5 character subword pieces on average
        for (let i = 0; i < part.length; i += 5) {
          segments.push(part.slice(i, i + 5));
        }
      }
    }
  }

  return {
    tokenCount: segments.length,
    byteLength,
    charLength,
    segments,
    method: 'deterministic-bpe-subword-v1'
  };
}

/**
 * Estimates USD inference cost for a given input and output token count across representative model pricing tiers.
 * Explicitly labeled as estimated from published per-million-token rates.
 *
 * @param {number} inputTokens - Total input tokens consumed by receiver(s).
 * @param {number} outputTokens - Total output tokens generated by sender(s).
 * @returns {{ frontierTierUsd: number, balancedTierUsd: number, fastTierUsd: number, pricingBasis: string }}
 */
function estimateInferenceCost(inputTokens, outputTokens) {
  const safeIn = Math.max(0, Number(inputTokens) || 0);
  const safeOut = Math.max(0, Number(outputTokens) || 0);

  // Representative pricing per 1M tokens:
  // Frontier ($3.00 / 1M in, $15.00 / 1M out)
  // Balanced ($1.25 / 1M in, $5.00 / 1M out)
  // Fast/Open-Weight ($0.25 / 1M in, $1.00 / 1M out)
  const frontierTierUsd = Number(((safeIn * 3.0 + safeOut * 15.0) / 1_000_000).toFixed(6));
  const balancedTierUsd = Number(((safeIn * 1.25 + safeOut * 5.0) / 1_000_000).toFixed(6));
  const fastTierUsd = Number(((safeIn * 0.25 + safeOut * 1.0) / 1_000_000).toFixed(6));

  return {
    frontierTierUsd,
    balancedTierUsd,
    fastTierUsd,
    pricingBasis: 'estimated-usd-per-1m-tokens (frontier: $3/$15, balanced: $1.25/$5, fast: $0.25/$1)'
  };
}

module.exports = {
  estimateTokens,
  estimateInferenceCost
};
